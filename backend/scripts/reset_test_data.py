"""Manual tool: wipe the pipeline's generated TEST DATA while keeping the InfoBeans setup — not
part of the app, not imported by anything.

Wiped  (generated by discovery / enrichment / qualification / drafting):
    outreach_activities, drafts, recommendations, role_relevance_results, qualification_results,
    contact_channels, contacts, enrichment_records, companies, ingestion_runs, jobs
Kept   (the InfoBeans setup, plus the org everything hangs off):
    products, offering_proposals, offering_pages, qualification_criteria, role_categories,
    organizations, users

Before wiping, the current results are saved to backend/logs/ab_runs.txt (labelled with the
current COMPANY_DATA_SOURCE) so a run's evidence is never lost; --skip-snapshot turns that off
(use it for the first wipe, when what's in the DB is old test data, not a run to compare).

Dry run by default: prints what WOULD be deleted and what is kept, changes nothing. A real wipe
needs --yes AND typing "wipe" at the prompt. Stop the job worker first, or an in-flight job could
write rows back in right after the wipe.

Usage (from backend/, venv active):
    python scripts/reset_test_data.py            # dry run
    python scripts/reset_test_data.py --yes      # asks for confirmation, then wipes
"""

import argparse
import asyncio
import sys

from sqlalchemy import text

from app.core.logging import configure_logging
from app.db.session import SessionLocal

# One TRUNCATE listing every table in the set: Postgres permits it because every FK-linked table
# is named in the same statement, so no CASCADE is needed (and none is wanted — a CASCADE from
# the wrong table would silently reach the kept config tables).
WIPE_TABLES = (
    "outreach_activities",
    "drafts",
    "recommendations",
    "role_relevance_results",
    "qualification_results",
    "contact_channels",
    "contacts",
    "enrichment_records",
    "companies",
    "ingestion_runs",
    "jobs",
)
KEEP_TABLES = (
    "products",
    "offering_proposals",
    "offering_pages",
    "qualification_criteria",
    "role_categories",
    "organizations",
    "users",
)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--yes", action="store_true", help="actually wipe (still asks to confirm)")
    parser.add_argument(
        "--skip-snapshot", action="store_true", help="don't save current results before wiping"
    )
    return parser.parse_args()


async def _counts(tables: tuple[str, ...]) -> dict[str, int]:
    async with SessionLocal() as session:
        return {
            table: (await session.execute(text(f"SELECT count(*) FROM {table}"))).scalar_one()
            for table in tables
        }


def _print_counts(title: str, counts: dict[str, int]) -> None:
    print(f"\n{title}")
    for table, n in counts.items():
        print(f"  {table:<26}{n:>8}")


async def _active_jobs() -> int:
    async with SessionLocal() as session:
        count: int = (
            await session.execute(
                text("SELECT count(*) FROM jobs WHERE status IN ('pending', 'running')")
            )
        ).scalar_one()
        return count


async def _main() -> int:
    configure_logging()
    args = _parse_args()

    kept_before = await _counts(KEEP_TABLES)
    wipe_before = await _counts(WIPE_TABLES)
    _print_counts("WILL BE WIPED" if args.yes else "WOULD BE WIPED (dry run)", wipe_before)
    _print_counts("KEPT (never touched)", kept_before)

    active = await _active_jobs()
    if active:
        print(f"\nWARNING: {active} job(s) are pending/running. Stop the worker before wiping.")

    if not args.yes:
        print("\nDry run only. Re-run with --yes to wipe.")
        return 0

    if input('\nType "wipe" to delete the rows listed above: ').strip() != "wipe":
        print("Aborted, nothing changed.")
        return 1

    if wipe_before["companies"] and not args.skip_snapshot:
        # Imported lazily: it's a sibling script, only needed on a real wipe.
        from ab_snapshot import LOG_PATH, snapshot

        from app.core.config import get_settings

        await snapshot(get_settings().company_data_source)
        print(f"\nSaved the current results to {LOG_PATH} before wiping.")

    async with SessionLocal() as session:
        await session.execute(text(f"TRUNCATE {', '.join(WIPE_TABLES)}"))
        await session.commit()

    _print_counts("AFTER - wiped tables", await _counts(WIPE_TABLES))
    kept_after = await _counts(KEEP_TABLES)
    _print_counts("AFTER - kept tables", kept_after)
    if kept_after != kept_before:
        print("\nERROR: kept-table counts changed. Investigate before continuing.")
        return 2
    print("\nDone. Kept tables unchanged.")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    sys.exit(asyncio.run(_main()))
